from MoinMoin import user, wikiutil
from MoinMoin.Page import Page
from MoinMoin.widget import html


def account_form(context, uid, operation, label):
    form = html.FORM(action=context.page.url(context), method='POST')
    ticket = wikiutil.createTicket(context, action='userprofile')
    if operation == 'confirm-delete':
        confirmation = wikiutil.createTicket(context, action='userprofile-delete/' + uid)
        form.append(html.INPUT(type='hidden', name='confirmation', value=confirmation))
    for name, value in (('action', 'userprofile'), ('uid', uid),
                        ('operation', operation), ('ticket', ticket)):
        form.append(html.INPUT(type='hidden', name=name, value=value))
    form.append(html.INPUT(type='submit', value=label))
    return str(form)


def execute(pagename, context):
    _ = context.getText
    form = context.request.form
    page = Page(context, pagename)
    if not context.user.isSuperUser():
        context.theme.add_msg(_("Only superuser is allowed to use this action."), 'error')
    elif context.request.method == 'POST' and wikiutil.checkTicket(context, form.get('ticket', '')):
        uid = form.get('uid')
        operation = form.get('operation')
        # Accept the enable/disable form generated by older cached pages.
        if not uid and form.get('key') == 'disabled' and form.get('val') in {'0', '1'}:
            uid = user.getUserId(context, form.get('name'), include_disabled=True)
            operation = 'disable' if form['val'] == '1' else 'enable'
        if uid not in user.getUserList(context):
            context.theme.add_msg(_('User account was not found.'), 'error')
        else:
            account = user.User(context, uid)
            if operation == 'delete':
                prompt = _('Permanently delete the account for "%s"?') % account.name
                confirmation = account_form(context, uid, 'confirm-delete', _('Permanently delete account'))
                context.theme.add_msg(wikiutil.escape(prompt) + confirmation, 'dialog')
            elif operation == 'confirm-delete' and not wikiutil.checkTicket(
                    context, form.get('confirmation', ''), action='userprofile-delete/' + uid):
                context.theme.add_msg(_('Confirm this deletion in the account browser.'), 'error')
            elif operation in {'disable', 'enable', 'confirm-delete'}:
                messages = {
                    'disable': _('User account "%s" disabled.'),
                    'enable': _('User account "%s" enabled.'),
                    'confirm-delete': _('User account "%s" deleted.'),
                }
                try:
                    if operation == 'confirm-delete':
                        changed = account.delete()
                    elif operation == 'disable':
                        changed = account.disable()
                    else:
                        changed = account.enable()
                except user.AccountIdentityConflict:
                    context.theme.add_msg(_('Another profile uses this account name or email.'), 'error')
                else:
                    if changed and uid == context.user.id and operation != 'enable':
                        context.user = user.User(context, auth_method='invalid')
                    message = messages[operation] if changed else _('No change to user account "%s".')
                    context.theme.add_msg(message % wikiutil.escape(account.name), 'info')
    page.send_page()
